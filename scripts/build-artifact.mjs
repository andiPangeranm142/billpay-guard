/**
 * build-artifact.mjs - regenerate contracts/BillPayGuard.artifact.ts from
 * the solc compiler output in out/.
 *
 * Run after editing contracts/BillPayGuard.sol:
 *   npm run compile
 *
 * This keeps the committed artifact (ABI + creation bytecode) exactly in
 * sync with the Solidity source: no hand-copying, no drift.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, "..");
const abiPath = path.join(root, "out", "contracts_BillPayGuard_sol_BillPayGuard.abi");
const binPath = path.join(root, "out", "contracts_BillPayGuard_sol_BillPayGuard.bin");

const abi = JSON.parse(fs.readFileSync(abiPath, "utf8"));
const bin = fs.readFileSync(binPath, "utf8").trim();
if (!/^[0-9a-fA-F]+$/.test(bin) || bin.length === 0) {
  throw new Error("Unexpected bytecode output from solc.");
}

const header = `// AUTO-GENERATED by scripts/build-artifact.mjs from contracts/BillPayGuard.sol
// (solc 0.8.24, --optimize). Do not edit by hand; run \`npm run compile\`.
`;
const body =
  header +
  `export const billPayGuardAbi = ${JSON.stringify(abi, null, 2)} as const;\n\nexport const billPayGuardBytecode = "0x${bin}" as const;\n`;

fs.writeFileSync(path.join(root, "contracts", "BillPayGuard.artifact.ts"), body);
console.log(`Wrote contracts/BillPayGuard.artifact.ts (${abi.length} ABI entries, ${bin.length / 2} bytes of bytecode).`);
