/**
 * build-artifact.mjs - regenerate contracts/BillPayGuard.artifact.ts (and
 * the test-only attacker artifact) from the solc compiler output in out/.
 *
 * Run after editing contracts/BillPayGuard.sol or
 * contracts/test/ReentrantAttacker.sol:
 *   npm run compile
 *
 * This keeps the committed artifacts (ABI + creation bytecode) exactly in
 * sync with the Solidity source: no hand-copying, no drift.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(dir, "..");

/** Read one contract's ABI + bytecode out of solc's out/ directory. */
function readSolcOutput(sourceFile, contractName) {
  const stem = `${sourceFile.replace(/[/.]/g, "_")}_${contractName}`;
  const abi = JSON.parse(fs.readFileSync(path.join(root, "out", `${stem}.abi`), "utf8"));
  const bin = fs.readFileSync(path.join(root, "out", `${stem}.bin`), "utf8").trim();
  if (!/^[0-9a-fA-F]+$/.test(bin) || bin.length === 0) {
    throw new Error(`Unexpected bytecode output from solc for ${contractName}.`);
  }
  return { abi, bin };
}

/** Write one artifact file: ABI + bytecode as const exports. */
function writeArtifact(outPath, header, exports) {
  const body =
    header +
    exports
      .map(
        ([name, value]) =>
          `export const ${name} = ${typeof value === "string" ? `"${value}"` : JSON.stringify(value, null, 2)} as const;\n`,
      )
      .join("\n");
  fs.writeFileSync(path.join(root, outPath), body);
  console.log(`Wrote ${outPath}.`);
}

// BillPayGuard — the live contract.
{
  const { abi, bin } = readSolcOutput("contracts/BillPayGuard.sol", "BillPayGuard");
  writeArtifact(
    "contracts/BillPayGuard.artifact.ts",
    `// AUTO-GENERATED by scripts/build-artifact.mjs from contracts/BillPayGuard.sol\n// (solc 0.8.24, --optimize). Do not edit by hand; run \`npm run compile\`.\n`,
    [
      ["billPayGuardAbi", abi],
      ["billPayGuardBytecode", `0x${bin}`],
    ],
  );
  console.log(`  (${abi.length} ABI entries, ${bin.length / 2} bytes of bytecode)`);
}

// ReentrantAttacker — TEST ONLY (see contracts/test/ReentrantAttacker.sol).
{
  const payee = readSolcOutput("contracts/test/ReentrantAttacker.sol", "ReentrantPayee");
  const withdrawer = readSolcOutput("contracts/test/ReentrantAttacker.sol", "ReentrantWithdrawer");
  writeArtifact(
    "contracts/test/ReentrantAttacker.artifact.ts",
    `// AUTO-GENERATED by scripts/build-artifact.mjs from contracts/test/ReentrantAttacker.sol\n// (solc 0.8.24, --optimize). Do not edit by hand; run \`npm run compile\`.\n// TEST ONLY — the attacker contracts are never deployed to a live chain.\n`,
    [
      ["reentrantPayeeAbi", payee.abi],
      ["reentrantPayeeBytecode", `0x${payee.bin}`],
      ["reentrantWithdrawerAbi", withdrawer.abi],
      ["reentrantWithdrawerBytecode", `0x${withdrawer.bin}`],
    ],
  );
  console.log(
    `  (ReentrantPayee ${payee.bin.length / 2} bytes, ReentrantWithdrawer ${withdrawer.bin.length / 2} bytes)`,
  );
}
