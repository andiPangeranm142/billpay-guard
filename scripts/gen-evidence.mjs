/**
 * gen-evidence.mjs - generate src/evidence.ts from deployments/demo.json,
 * so the demo's Payment history can render the verified on-chain payments
 * without a wide eth_getLogs range (the Diana EVM node rejects wide log
 * ranges — even 10,000 blocks fails — and deploy-to-latest spans ~182,000
 * blocks, so a live scan of the full history is impossible).
 *
 * The recorded payments are the source of truth for the history table;
 * at runtime the demo re-verifies each one with a single-block getLogs
 * call (fromBlock == toBlock == the payment's block, always within the
 * node's range limit) and merges in any newer payments found by a short
 * backward scan from latest. One payment — the leashed payment at block
 * 10159020, executed inside a Cosmos MsgExecuteEVM — leaves no EVM log
 * at all, so the recorded entry is its only record.
 *
 * `paidQor` / `payments` are the cumulative schedule totals AFTER the
 * payment, read from the on-chain PaymentExecuted event args (verified
 * 19 Nov 2026 with single-block getLogs calls).
 *
 * If demo.json does not exist yet, it writes a module with an empty
 * payment list instead of failing the build.
 *
 * Run: node scripts/gen-evidence.mjs (also runs as the `prebuild` step).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const demoPath = path.resolve(dir, "..", "deployments", "demo.json");
const outPath = path.resolve(dir, "..", "src", "evidence.ts");

const header = `/**
 * evidence.ts - GENERATED by scripts/gen-evidence.mjs from
 * deployments/demo.json. Do not edit by hand; re-run the generator.
 *
 * The verified on-chain payment history of the BillPayGuard demo: every
 * real PaymentExecuted event, with the EVM (and, where it exists, the
 * Cosmos) transaction hash. The demo renders these rows immediately and
 * re-verifies each one against the chain with a single-block getLogs
 * call; the leashed payment (block 10159020) has no EVM log, so its
 * recorded entry is the only record of it.
 */

export type RecordedPayment = {
  /** Schedule id the payment belongs to. */
  scheduleId: number;
  /** Schedule owner (the guard account that funded the payment). */
  owner: string;
  /** Payee address of the schedule. */
  payee: string;
  /** Amount of this payment, in QOR (decimal string). */
  amountQor: string;
  /** Cumulative amount paid on the schedule AFTER this payment, in QOR. */
  paidQor: string;
  /** Cumulative payment count on the schedule AFTER this payment. */
  payments: number;
  /** Block the payment landed in. */
  block: number;
  /** EVM transaction hash — absent for the leashed (MsgExecuteEVM) payment. */
  evmTx?: string;
  /** Cosmos transaction hash, where one was recorded. */
  cosmosTx?: string;
  /** Who executed the payment ("agent" or "agent (leashed)"). */
  executedBy: string;
  /** ISO timestamp the payment executed. */
  executedAt: string;
};

`;

let demo = null;
try {
  demo = JSON.parse(fs.readFileSync(demoPath, "utf8"));
} catch {
  // No demo run yet — the page renders without recorded payments.
}

if (!demo || !Array.isArray(demo.agentPayments)) {
  fs.writeFileSync(outPath, header + "export const RECORDED_PAYMENTS: RecordedPayment[] = [];\n");
  console.log("gen-evidence: no deployments/demo.json agentPayments yet; wrote an empty evidence module.");
  process.exit(0);
}

const payeeBySchedule = new Map(
  (demo.schedules ?? []).map((s) => [s.id, s.payee]),
);

const payments = demo.agentPayments.map((p) => {
  const row = {
    scheduleId: p.scheduleId,
    owner: demo.owner,
    payee: payeeBySchedule.get(p.scheduleId) ?? "",
    amountQor: p.amountQor,
    paidQor: p.paidQor,
    payments: p.payments,
    block: p.block,
    executedBy: p.executedBy,
    executedAt: p.executedAt,
  };
  if (p.evmTx) row.evmTx = p.evmTx;
  if (p.cosmosTx) row.cosmosTx = p.cosmosTx;
  return row;
});

payments.sort((a, b) => a.block - b.block);

fs.writeFileSync(
  outPath,
  header + `export const RECORDED_PAYMENTS: RecordedPayment[] = ${JSON.stringify(payments, null, 2)};\n`,
);
console.log(`gen-evidence: wrote src/evidence.ts (${payments.length} recorded payments).`);
